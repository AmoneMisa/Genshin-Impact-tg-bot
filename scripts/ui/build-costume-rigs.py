"""Publish reviewed animation landmarks and create magnified face QA sheets.

Only metadata is published; original image pixels are never modified.
"""
import json
from pathlib import Path
from PIL import Image, ImageDraw

root = Path(__file__).resolve().parents[2]
folder = root / 'art-source/avatars/motion-review'
landmarks = json.loads((folder / 'landmarks.json').read_text(encoding='utf-8-sig'))
jobs = json.loads((root / 'art-source/avatars/collections/jobs.json').read_text(encoding='utf-8-sig'))
reviewed = json.loads((root / 'art-source/avatars/collections/reviewed.json').read_text(encoding='utf-8-sig'))
races = ['human', 'elf', 'darkElf', 'orc', 'dwarf', 'kamael']
calibrated = json.loads((folder / 'calibrated-eyes.json').read_text(encoding='utf-8'))
poses = json.loads((folder / 'pose-motion.json').read_text(encoding='utf-8'))
wings = json.loads((folder / 'wing-motion.json').read_text(encoding='utf-8'))
rigs = {}
qa = []

def add(path, points, race, gender, key):
    assert path in poses, 'Missing individual pose review: '+key
    dwarf = race == 'dwarf'
    if points:
        x, y, distance, tilt = points
        face = [x / 300, y / 450]
        rx = .026 if dwarf and gender == 'female' else .020 if dwarf else .016
        ry = .018 if dwarf and gender == 'female' else .0065
        rx = min(rx, abs(calibrated[key][1][0]-calibrated[key][0][0])/3.5)
        eyes = [[ex,ey,rx,ry] for ex,ey in calibrated[key]]
        face = [sum(e[0] for e in eyes)/2, sum(e[1] for e in eyes)/2]
    else:
        face, eyes = [.5, .15], []  # Fully closed helmet: no invented eyes.
    cx, cy = face
    hair = [] if not points else [[cx-.085,cy+.065,.05,.08,1], [cx+.085,cy+.065,.05,.08,1]]
    if dwarf and gender == 'male': hair = [[cx,cy+.095,.09,.05,.5]]  # Beard, bald crown stays still.
    cloth = [[cx-.17,.67,.14,.13,.75], [cx+.17,.67,.14,.13,.75]]
    phase = (sum(map(ord,key)) % 29) / 10
    def rounded(value):
        return [rounded(x) for x in value] if isinstance(value,list) else round(value,6)
    rigs[path] = {'face':rounded(face),'eyes':rounded(eyes),'hair':rounded(hair),'cloth':rounded(cloth),'phase':phase}
    # Fitted torso, waist and legs stay stable; only free edges use cloth motion.
    rigs[path].update(breathStrength=.7, clothStart=.50,
                      fixedAreas=[[cx-.105,cy+.16,cx+.105,.54,.025],
                                  [cx-.105,.74,cx+.105,.96,.018]])
    rigs[path].update(poses[path])
    rigs[path]['breathStrength'] = .7
    if race == 'kamael': rigs[path]['wing'] = wings[key]
    qa.append((key, path, points))

for job in jobs:
    if job['key'] not in reviewed: continue
    points = landmarks[job['costumeId']][races.index(job['race'])]
    add('/art/avatars/collections/v1/'+job['key'], points, job['race'], job['gender'], job['key'])

defaults = json.loads((folder/'default-items.json').read_text())
default_points = [[141,53,14,4],[141,57,13,-2],[163,51,15,4],[139,56,13,-1],
                  [169,57,14,4],[148,55,14,2],[170,49,14,4],[147,51,12,0],
                  [162,68,24,0],[160,106,31,6],[144,53,13,3],[134,65,13,-2]]
for (key,file),points in zip(defaults,default_points):
    race, gender = key.split('-')
    add('/'+file.removeprefix('webapp/').removesuffix('-512.webp'),points,race,gender,key)

for batch in range(0,len(qa),12):
    sheet=Image.new('RGB',(1200,600),(25,30,43))
    draw=ImageDraw.Draw(sheet)
    for i,(key,path,points) in enumerate(qa[batch:batch+12]):
        if not points: continue
        x,y,dist,tilt=points
        im=Image.open(root/('webapp'+path+'-512.webp')).convert('RGBA')
        left,top=round((x-35)*512/300),round((y-23)*768/450)
        crop=im.crop((left,top,left+120,top+80)).resize((240,160))
        px,py=(i%4)*300,(i//4)*200
        sheet.paste(crop,(px,py+25),crop)
        draw.text((px,py+3),str(batch+i)+' '+key,fill='white')
        for ex,ey,rx,ry in rigs[path]['eyes']:
            sx=px+(ex*512-left)*2;sy=py+25+(ey*768-top)*2
            # Keep the painted eye visible between tick marks.
            draw.line((sx-10,sy,sx-5,sy),fill='red',width=1)
            draw.line((sx+5,sy,sx+10,sy),fill='red',width=1)
            draw.line((sx,sy-10,sx,sy-5),fill='red',width=1)
            draw.line((sx,sy+5,sx,sy+10),fill='red',width=1)
    sheet.save(folder/f'eye-qa-{batch//12}.jpg')
target = root/'webapp/art/avatar-costume-rigs.js'
target.write_text('// Reviewed painting coordinates, generated by build-costume-rigs.py.\n'
                  +'export const AVATAR_COSTUME_RIGS = '+json.dumps(rigs,ensure_ascii=False,separators=(',',':'))+';\n'
                  +'export function avatarCostumeRig(src = "") { return AVATAR_COSTUME_RIGS[src.split("?")[0].replace(/-(256|512|1024)\\.webp$/, "")] || null; }\n',encoding='utf-8')
print('Published',len(rigs),'painting rigs; QA sheets:',(len(qa)+11)//12)
