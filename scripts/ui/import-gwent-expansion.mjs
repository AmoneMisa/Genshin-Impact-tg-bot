import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
const root=path.resolve('output/gwent-review'),dest=path.resolve('webapp/art/gwent/expansion');
const normal={},extended={},sources={};
fs.mkdirSync(dest,{recursive:true});
for(const name of fs.readdirSync(root)){
 const folder=path.join(root,name),file=path.join(folder,'deck-manifest.json');
 if(!fs.existsSync(file))continue;
 const manifest=JSON.parse(fs.readFileSync(file));assert.equal(manifest.complete,true,name+' is incomplete');
 for(const card of manifest.cards){
  if(card.reuse||(!card.nativePatch&&card.quoteOrigin!=='fan-written'))continue;
  const key=(card.nativePatch?'extended-':'')+card.id,source=path.join(folder,card.webp);
  const hash=crypto.createHash('sha256').update(fs.readFileSync(source)).digest('hex');
  if(sources[key])assert.equal(sources[key].sha256,hash,'Conflicting faces for '+key);
  fs.copyFileSync(source,path.join(dest,key+'.webp'));
  (card.nativePatch?extended:normal)[card.id]='/art/gwent/expansion/'+key+'.webp';
  sources[key]={package:name,id:card.id,sha256:hash};
 }
}
const sorted=obj=>Object.fromEntries(Object.entries(obj).sort(([a],[b])=>a.localeCompare(b)));
fs.writeFileSync('webapp/gwent-expansion-art.js',`// Generated by scripts/ui/import-gwent-expansion.mjs from reviewed printed faces.\n// Extended-only face overrides do not replace the classic card or add entities.\nexport const EXPANSION_GWENT_ART=Object.freeze(${JSON.stringify(sorted(normal),null,2)});\nexport const EXTENDED_GWENT_ART=Object.freeze(${JSON.stringify(sorted(extended),null,2)});\n`);
fs.writeFileSync(path.join(dest,'README.md'),`# Reviewed Gwent faces\n\nImported losslessly from the review packages as their ready WebP faces. One runtime file per canonical card; common cards are deduplicated. Extended-only badge changes have separate files, selected by ruleset. Existing original artwork and cosmetic variants are retained. Printed names, numbers and quotes are already inside the images.\n\nRegenerate: node scripts/ui/import-gwent-expansion.mjs\n\n${Object.entries(sorted(sources)).map(([id,s])=>`- ${id}: output/gwent-review/${s.package}/cards/${s.id}.webp; SHA-256 ${s.sha256}`).join('\n')}\n`);
console.log(JSON.stringify({newFaces:Object.keys(normal).length,extendedOverrides:Object.keys(extended).length,output:dest}));
