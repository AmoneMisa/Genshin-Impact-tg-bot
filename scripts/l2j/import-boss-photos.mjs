// Preserve original Lineage II NPC screenshots; never substitute unrelated bosses.
import fs from 'node:fs';
import {worldRows, EPIC_NPC} from '../../functions/game/boss/worldBosses.js';

const target = 'webapp/art/bosses/l2';
fs.mkdirSync(target, {recursive: true});
const rows = [...worldRows.map(row => ({id: row.id, name: row.name})),
  ...Object.entries(EPIC_NPC).map(([id, name]) => ({id: Number(id), name}))];
const assets = {};
const missing = [];
const epicNames = {queenAnt: 'Queen Ant', core: 'Core', orfen: 'Orfen', zaken: 'Zaken', baium: 'Baium', frintezza: 'Frintezza', antharas: 'Antharas', valakas: 'Valakas', beleth: 'Beleth', freya: 'Freya', freyaExtreme: 'Freya'};
const previous = fs.existsSync(`${target}/manifest.json`) ? JSON.parse(fs.readFileSync(`${target}/manifest.json`, 'utf8')).assets : {};
const get = url => fetch(url, {signal: AbortSignal.timeout(15000)});
const extension = data => data.toString('ascii', 0, 4) === 'RIFF' && data.toString('ascii', 8, 12) === 'WEBP' ? 'webp'
  : data[0] === 0xff && data[1] === 0xd8 ? 'jpg' : data.subarray(0, 8).toString('hex') === '89504e470d0a1a0a' ? 'png' : null;
async function download(source) {
  const response = await get(source);
  if (!response.ok) throw new Error(`HTTP ${response.status}`);
  const data = Buffer.from(await response.arrayBuffer());
  if (!extension(data) || data.length === 10356 || data.length === 54746) throw new Error('Not an NPC screenshot');
  return {data, source};
}
async function original(row) {
  const cached = previous[row.name];
  if (cached && fs.existsSync(`webapp${cached.image}`)) {
    const data = fs.readFileSync(`webapp${cached.image}`);
    if (extension(data) && data.length !== 10356 && data.length !== 54746) return {data, source: cached.source};
    fs.unlinkSync(`webapp${cached.image}`);
  }
  try { return await download(`https://l2elo.com/images/npc-photos/${row.id}.webp`); } catch {}
  const name = epicNames[row.name] || row.name;
  try {
    const page = await (await get(`https://linedia.ru/wiki/${encodeURIComponent(name.replaceAll(' ', '_'))}`)).text();
    const src = page.match(/<img[^>]+src="([^"]*(?:Screenshot|screenshot)[^"]+)"/)?.[1];
    if (src) return await download(new URL(src.replaceAll('&amp;', '&'), 'https://linedia.ru').href);
  } catch {}
  for (const chronicle of ['freya', 'gracia']) {
    try {
      const page = await (await get(`https://l2db.ru/npc/view/${row.id}/${chronicle}/`)).text();
      const src = page.match(/<img[^>]+src="([^"]*user_images\/[^"]+)"/)?.[1];
      if (src) return await download(new URL(src, 'https://l2db.ru').href);
    } catch {}
  }
  if (row.name === 'beleth') return download('https://lineage2dex.com/template/site/dex/storage/images/beleth.jpg');
  throw new Error('Original screenshot not found');
}
let cursor = 0;
await Promise.all(Array.from({length: 6}, async () => {
  while (cursor < rows.length) {
    const row = rows[cursor++];
    try {
      const {data, source} = await original(row);
      const ext = extension(data);
      const file = `${target}/${row.id}.${ext}`;
      fs.writeFileSync(file, data);
      assets[row.name] = {npcId: row.id, image: `/art/bosses/l2/${row.id}.${ext}`, source};
    } catch (error) { missing.push({...row, error: error.message}); }
  }
}));
const sorted = Object.fromEntries(Object.entries(assets).sort(([a], [b]) => a.localeCompare(b)));
fs.writeFileSync('webapp/l2-boss-art.js', `// Original Lineage II NPC screenshots. Generated by scripts/l2j/import-boss-photos.mjs.\nexport default ${JSON.stringify(sorted, null, 2)};\n`);
fs.writeFileSync(`${target}/manifest.json`, JSON.stringify({providers: ['L2ELO', 'Linedia', 'L2DB', 'Lineage2Dex'], assets: sorted, missing}, null, 2));
console.log(JSON.stringify({downloaded: Object.keys(assets).length, missing}));
