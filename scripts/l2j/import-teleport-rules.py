"""Import the pinned H5 teleporter setting from cached original sources."""
import hashlib
import json
import re
from pathlib import Path

files={'dist/game/config/Player.ini':Path('.tmp/geodata/Player.ini'),
       'java/org/l2jmobius/gameserver/entity/teleporter/TeleportHolder.java':Path('.tmp/geodata/TeleportHolder.java')}
setting=re.search(r'^TeleportWhileSiegeInProgress\s*=\s*(True|False)\s*$',files['dist/game/config/Player.ini'].read_text(encoding='utf-8'),re.M|re.I)
assert setting, 'Original Player.ini setting missing'
java=next(p for f,p in files.items() if f.endswith('.java')).read_text(encoding='utf-8')
assert 'TELEPORT_WHILE_SIEGE_IN_PROGRESS' in java and 'loc.getCastleId()' in java
data={'teleportWhileSiegeInProgress':setting[1].lower()=='true','source':{
    'commit':'9fb01cb20513e55190cdde8d91e41be2c0914f84',
    'repository':'https://gitlab.com/MobiusDevelopment/L2J_Mobius',
    'setting':'TeleportWhileSiegeInProgress',
    'files':{f:hashlib.sha256(p.read_bytes()).hexdigest() for f,p in files.items()}}}
Path('template/teleportRules.js').write_text('// Pinned High Five policy; generated by scripts/l2j/import-teleport-rules.py.\nexport default '+json.dumps(data,indent=2)+';\n',encoding='utf-8')
print('Teleport while siege:',data['teleportWhileSiegeInProgress'])
