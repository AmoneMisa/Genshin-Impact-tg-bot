"""Publish explicit source NPC points for walking; never invent a teleport tariff."""
import hashlib
import json
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

base=next(Path('.tmp/world-source/h5-data').glob('*/L2J*/dist/game/data'))
config={"sel-mahums":("oren","spawns/Oren/SelMahums.xml",22775,(88347,56413,-3495)),'vuku-lands':('gludio','spawns/Others/19_21.xml',20011,(-12420,99284,-3066))}
world=json.loads(Path('template/nativeWorld.js').read_text(encoding='utf-8').split('export default ',1)[1].strip().rstrip(';'))
file=Path('template/nativeSpawnEntries.js')
entries=json.loads(file.read_text(encoding='utf-8').split('export default ',1)[1].strip().rstrip(';'))
ids=sys.argv[1:]
assert ids and all(id in config for id in ids), 'Supply configured source location IDs'
for id in ids:
    city,path,npc,xyz=config[id];source=base/path
    row=next(n for n in ET.parse(source).iter('npc') if n.get('id')==str(npc) and all(n.get(k)==str(v) for k,v in zip(['x','y','z'],xyz)))
    x,y,z=(int(row.get(k)) for k in ['x','y','z'])
    entries[id]={'x':x,'y':y,'z':z,'region':city,'teleportGold':None,'entryRoutes':[],
        'access':{'kind':'walk-only'},'entrySource':{'file':path,'npcId':npc,'type':'NPC_SPAWN',
        'coordinateSource':'point','commit':world['source']['commit'],'sha256':hashlib.sha256(source.read_bytes()).hexdigest()},
        'polygon':[[x-5000,y-5000],[x+5000,y-5000],[x+5000,y+5000],[x-5000,y+5000]],'selectionGeometry':'authored-extent'}
    print(id,'original NPC',npc,'point',xyz,'walking only; teleport tariff unverified')
file.write_text('// Original NPC point anchors; generated by scripts/l2j/import-native-spawn-entries.py.\nexport default '+json.dumps(entries,ensure_ascii=False,indent=2)+';\n',encoding='utf-8')
