"""Publish H5 NPC aggression and social clans for the actual hunting catalog."""
from pathlib import Path
import json
import subprocess
import xml.etree.ElementTree as ET

root = Path(__file__).resolve().parents[2]
ids = json.loads(subprocess.check_output([
    'node', '--input-type=module', '-e',
    "import {getZones} from './functions/game/hunt/huntMobs.js'; console.log(JSON.stringify([...new Set(getZones().flatMap(z=>z.mobs.map(m=>String(m.id))))]));"
], cwd=root, text=True))
rows = {}
for path in sorted((root / '.tmp/hf-npcs').glob('*.xml')):
    for npc in ET.parse(path).getroot().findall('npc'):
        if npc.get('id') not in ids:
            continue
        ai = npc.find('ai')
        if ai is None:
            continue
        rows[npc.get('id')] = {
            'aggressive': ai.get('isAggressive') == 'true',
            'aggroRange': int(ai.get('aggroRange', '0')),
            'clanHelpRange': int(ai.get('clanHelpRange', '0')),
            'clans': [e.text for e in ai.findall('./clanList/clan') if e.text],
            'ignoredIds': [e.text for e in ai.findall('./clanList/ignoreNpcId') if e.text],
            'type': ai.get('type', 'FIGHTER'),
        }
missing = sorted(set(ids) - rows.keys())
header = '// H5 NPC XML snapshot 9fb01cb20513e55190cdde8d91e41be2c0914f84. Generated by scripts/l2j/import-npc-ai.py.\n'
(root / 'template/l2NpcAi.js').write_text(header + 'export const MISSING_NPC_AI = ' + json.dumps(missing) + ';\nexport default ' + json.dumps(rows, sort_keys=True, separators=(',', ':')) + ';\n', encoding='utf-8')
print(f'NPC AI: {len(rows)} imported, {len(missing)} explicitly missing')
