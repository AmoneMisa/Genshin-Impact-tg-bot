"""Import original High Five epic jewelry and their permanent passive skills."""
import json
from pathlib import Path
import xml.etree.ElementTree as ET
IDS={6656,6657,6658,6659,6660,6661,6662,8191,10314,16025,16026,21712,10170}
def tree(e):
 return {'tag':e.tag,**e.attrib,**({'value':e.text.strip()} if e.text and e.text.strip() else {}),**({'children':[tree(c) for c in e]} if len(e) else {})}
items={};skills={};needed=set()
for p in Path('.tmp/l2-high-five/items').rglob('*.xml'):
 for e in ET.parse(p).getroot().findall('item'):
  id=int(e.get('id'))
  if id not in IDS:continue
  sets={c.get('name'):c.get('val') for c in e.findall('set')}
  stats={c.get('type'):float(c.text) for c in e.findall('./stats/stat')}
  # Some datapacks use stats at the root; preserve the actual numeric values.
  stats.update({c.get('type'):float(c.text) for c in e.findall('.//stat') if c.text})
  passive=[{'id':int(c.get('id')),'level':int(c.get('level'))} for c in e.findall('.//skill')]
  needed.update(c['id'] for c in passive)
  items[id]={'itemId':id,'name':e.get('name'),'grade':sets['crystal_type'],**stats,'weight':int(sets['weight']),'price':int(sets['price']),'icon':sets['icon'],'skills':passive}
for p in Path('.tmp/l2-high-five/all-skills').rglob('*.xml'):
 for s in ET.parse(p).getroot().findall('skill'):
  id=int(s.get('id'))
  if id not in needed:continue
  skills[id]={'id':id,'name':s.get('name'),'levels':int(s.get('levels','1')),'operate':'P','fields':{c.tag:c.text.strip() for c in s if not len(c) and c.text and c.text.strip()},'tables':{t.get('name'):t.text.split() for t in s.findall('table') if t.text},'effects':[tree(e) for e in s.findall('./effects/effect')]}
assert len(items)==len(IDS) and len(skills)==len(needed)
Path('template/l2EpicJewelry.js').write_text('// Original High Five item values and passive skills. Generated by scripts/l2j/import-epic-jewelry.py.\nexport const EPIC_JEWELRY = '+json.dumps(items,ensure_ascii=False,indent=2)+';\nexport const EPIC_PASSIVES = '+json.dumps(skills,ensure_ascii=False,indent=2)+';\n',encoding='utf-8')
print('Imported',len(items),'items and',len(skills),'passives')
