// Import precise marginal drop probabilities, including outer group probability.
import fs from 'node:fs';
import WORLD from '../../template/worldBosses.js';
import LOOT from '../../template/l2Loot.js';
const root = 'https://db.ashenvale.club';
const sources = [[29001,'queenAnt',6660],[29006,'core',6662],[29014,'orfen',6661],[29022,'zaken',6659],[29020,'baium',6658],[29047,'frintezza',8191],[29068,'antharas',6656],[29028,'valakas',6657],[29118,'beleth',10314],[29179,'freya',16025],[29180,'freyaExtreme',16026],[29181,'zakenNighttime',21712],[29186,'balor',10170]];
const rows = await Promise.all(sources.map(async ([id,name,jewelId]) => {
 const response = await fetch(`${root}/api/get_npc`, {method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({sourceSlug:'highfive',npcId:id}),signal:AbortSignal.timeout(30000)});
 if (!response.ok) throw new Error(`NPC ${id}: HTTP ${response.status}`);
 const data = await response.json();
 if (!data.npc || !Array.isArray(data.drops)) throw new Error(`Invalid NPC ${id}`);
 const stats = Object.fromEntries(['level','hp','mp','pAtk','mAtk','pDef','mDef'].map(key=>[key,data.npc[key]]));
 stats.attackSpeed = data.npc.atkSpd;
 const drops = data.drops.map(drop => ({id:drop.itemId,name:drop.name,min:drop.min,max:drop.max,chance:drop.chance}));
 return {id,name,jewelId,url:`${root}/npc/highfive/${id}`,stats,drops};
}));
fs.writeFileSync('template/l2EpicReference.js', '// High Five NPC reference. Generated by scripts/l2j/audit-epics.mjs on 2026-10-11.\nexport default '+JSON.stringify(Object.fromEntries(rows.map(row=>[row.id,row])),null,2)+';\n');
const audit = rows.map(row => {
 const stored=WORLD.find(npc=>npc.id===row.id);
 const statDifferences=Object.fromEntries(Object.entries(row.stats).filter(([key,value])=>stored?.[key]!==value).map(([key,value])=>[key,{stored:stored?.[key],source:value}]));
 const old=LOOT[row.id]||[];
 return {...row,statDifferences,changedDropRows:row.drops.filter(drop=>!old.some(([id,min,max,chance])=>id===drop.id && min===drop.min && max===drop.max && Math.abs(chance-drop.chance)<1e-8))};
});
fs.writeFileSync('docs/epic-source-audit.json',JSON.stringify({checkedOn:'2026-10-11',bosses:audit},null,2));
console.log(JSON.stringify(audit.map(row=>({name:row.name,stats:row.statDifferences,drops:row.drops.length,jewel:row.drops.filter(drop=>drop.id===row.jewelId)}))));
