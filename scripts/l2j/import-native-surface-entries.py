"""Replace legacy map estimates with named NORMAL H5 destinations, one location at a time."""
import json
import hashlib
import sys
import xml.etree.ElementTree as ET
from pathlib import Path
base=next(Path('.tmp/world-source/h5-data').glob('*/L2J*/dist/game/data'))
config={'valley-of-saints':('rune','Valley of Saints'),'swamp-of-screams':('rune','Swamp of Screams'),'fields-of-massacre':('aden','Fields of Massacre'),'ketra-outpost':('goddard','Ketra Orc Outpost'),'varka-outpost':('goddard','Varka Silenos Stronghold')}
world=json.loads(Path('template/nativeWorld.js').read_text(encoding='utf-8').split('export default ',1)[1].strip().rstrip(';'))
file=Path('template/nativeSurfaceEntries.js')
entries=json.loads(file.read_text(encoding='utf-8').split('export default ',1)[1].strip().rstrip(';')) if file.exists() else {}
ids=sys.argv[1:]
assert ids and all(id in config for id in ids), 'Supply configured source location IDs'
for id in ids:
    city,name=config[id];keeper=world['towns'][city];source=base/f"teleporters/town/{keeper['npcId']}.xml"
    row=next(n for n in ET.parse(source).findall('.//teleport[@type="NORMAL"]/location') if n.get('name')==name)
    origin={'file':source.relative_to(base).as_posix(),'npcId':keeper['npcId'],'name':name,'type':'NORMAL','commit':world['source']['commit'],'sha256':hashlib.sha256(source.read_bytes()).hexdigest()}
    entries[id]={**{k:int(row.get(k)) for k in ['x','y','z']},'region':city,'teleportGold':int(row.get('feeCount')),'entrySource':origin,'entryRoutes':[{'npcId':keeper['npcId'],'npcName':keeper['name'],'type':'NORMAL','item':int(row.get('feeId','57')),'fee':int(row.get('feeCount')),'source':origin}]}
    x,y=entries[id]['x'],entries[id]['y']
    entries[id].update({'polygon':[[x-5000,y-5000],[x+5000,y-5000],[x+5000,y+5000],[x-5000,y+5000]],'selectionGeometry':'authored-extent'})
    print(id,name,'original entry and',row.get('feeCount'),'adena NORMAL route')
file.write_text('// Original named H5 surface entrances; generated by scripts/l2j/import-native-surface-entries.py.\nexport default '+json.dumps(entries,ensure_ascii=False,indent=2)+';\n',encoding='utf-8')
