"""Extract bare High Five class stats from the same pinned source as l2Classes.js."""
import json
import xml.etree.ElementTree as ET
from pathlib import Path

source = Path('.tmp/l2-high-five/players')
classes = {}
for path in source.rglob('*.xml'):
    if 'templates' not in path.parts:
        continue
    root = ET.parse(path).getroot()
    class_id = root.findtext('classId')
    static = root.find('staticData')
    if class_id is None or static is None:
        continue
    def scalar(name):
        node = static.find(name)
        if node is None:
            return 0
        if list(node):
            return sum(float(child.text) for child in node)
        return float(node.text)
    rows = {}
    for level in root.findall('lvlUpgainData/level'):
        rows[level.get('val')] = [float(level.findtext(key, '0')) for key in ['hp', 'mp', 'cp', 'hpRegen', 'mpRegen', 'cpRegen']]
    classes[class_id] = {
        'base': {key: scalar('base'+key) for key in ['STR', 'DEX', 'CON', 'INT', 'WIT', 'MEN', 'PAtk', 'MAtk', 'PDef', 'MDef']},
        'speed': float(static.findtext('baseMoveSpd/run', '120')),
        'levels': rows,
    }
assert len(classes) >= 70, 'Missing player template source'
Path('template/l2PlayerStats.js').write_text(
    '// Bare class stats, High Five source 9fb01cb20513e55190cdde8d91e41be2c0914f84. Generated by scripts/l2j/extract-player-stats.py.\n'
    + 'export default '+json.dumps(classes, separators=(',', ':'))+';\n', encoding='utf-8')
print(f'{len(classes)} class stat tables')
