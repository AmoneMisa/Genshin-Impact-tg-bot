"""Resize full original NPC screenshots; preserve aspect ratio, silhouette and colours."""
import json
import sys
from pathlib import Path
from PIL import Image, ImageOps

rows = json.loads(Path(sys.argv[1]).read_text(encoding='utf-8'))
target = Path('webapp/art/npcs/l2')
target.mkdir(parents=True, exist_ok=True)
provenance = target / 'source.js'
previous = json.loads(provenance.read_text(encoding='utf-8').split('export default ', 1)[1].rstrip().removesuffix(';'))['assets'] if provenance.exists() else {}
assets, missing = {}, []
for row in rows:
    if row.get('missing'):
        missing.append({k: v for k, v in row.items() if k != 'file'})
        continue
    try:
        old = previous.get(row['id'])
        if old and old['sha256'] == row['sha256'] and all((target / f"{row['id']}-{size}.webp").exists() for size in (128, 256)):
            assets[row['id']] = old
            continue
        with Image.open(row['file']) as source:
            if source.format not in ('WEBP', 'JPEG', 'PNG') or min(source.size) < 24:
                raise ValueError('Not a usable NPC screenshot')
            image = ImageOps.exif_transpose(source).convert('RGBA' if 'A' in source.getbands() else 'RGB')
            for size in (128, 256):
                preview = image.copy()
                preview.thumbnail((size, size), Image.Resampling.LANCZOS)
                preview.save(target / f"{row['id']}-{size}.webp", 'WEBP', quality=82, method=6)
            assets[row['id']] = {k: v for k, v in row.items() if k not in ('file', 'id')}
            assets[row['id']]['originalSize'] = list(source.size)
    except Exception as error:
        missing.append({'id': row['id'], 'name': row['name'], 'source': row['source'], 'missing': str(error)})

Path('webapp/art/l2-npc-art.js').write_text(
    '// Exact NPC IDs with locally published original L2 screenshots. Generated by import-npc-photos.mjs.\n'
    'const ids=new Set(' + json.dumps(list(assets), separators=(',', ':')) + ');\n'
    'export function npcPhotoUrl(npc,size=128){\n'
    " const id=String(npc?.npcId??npc?.mobId??npc?.id??'');\n"
    ' return ids.has(id)?`/art/npcs/l2/${id}-${size===256?256:128}.webp`:null;\n}\n', encoding='utf-8')
provenance.write_text(
    '// Screenshot provenance; resizing only. Not client icons or extracted 3D models.\n'
    'export default ' + json.dumps({'assets': assets, 'missing': missing}, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
total = sum(p.stat().st_size for p in target.glob('*.webp'))
Path('docs/l2-npc-images.md').write_text(
    '# Изображения NPC Lineage II\n\n'
    f'Подключены оригинальные скриншоты для {len(assets)} из {len(rows)} NPC текущего каталога охоты и рейд-боссов. '
    f'Два размера WebP (до 128 и 256 px), суммарно {total / 1024 / 1024:.2f} MiB. '
    'На игровом экране загружаются только изображения видимых NPC.\n\n'
    'Привязка строго по NPC ID High Five; нет подмены похожим существом или общим рисунком класса. '
    'Это скриншоты из баз Lineage II, а не клиентские иконки и не анимированные модели. '
    'Сохраняются фон и пропорции исходника; преобразование ограничено уменьшением и WebP. '
    'База изображений может содержать снимки из разных хроник; точное соответствие каждого снимка внешности High Five не подтверждено.\n\n'
    'Источники, SHA-256 исходников и размеры: `webapp/art/npcs/l2/source.js`. '
    'Обновление: `node scripts/l2j/import-npc-photos.mjs`; из локального кэша: добавить `--offline`.\n\n'
    '## Недоступные изображения\n\n'
    + ('Нет.\n' if not missing else '| NPC ID | Имя | Причина |\n| --- | --- | --- |\n'
       + '\n'.join(f"| {r['id']} | {r['name']} | {r['missing']} |" for r in missing) + '\n'), encoding='utf-8')
print(f'Published {len(assets)}/{len(rows)} original NPC screenshots; missing {len(missing)}; {total / 1024 / 1024:.2f} MiB', flush=True)
