"""Publish original client pixels by numeric skill/item ID for gameplay windows."""
import json,sys,zipfile
from pathlib import Path
import xml.etree.ElementTree as ET
from PIL import Image
icons=Path(sys.argv[1] if len(sys.argv)>1 else 'C:/Users/kubai/Desktop/icons')
skills_dir=Path(sys.argv[2] if len(sys.argv)>2 else '.tmp/l2-high-five/all-skills')
items_zip=Path(sys.argv[3] if len(sys.argv)>3 else '.tmp/l2-high-five/items.zip')
dest=Path('webapp/art/l2-extra');dest.mkdir(exist_ok=True)
text=Path('template/l2Classes.js').read_text(encoding='utf8')
classes=json.loads(text.split('export default ',1)[1].strip().rstrip(';'))
needed_skills=set(classes['skills'])|{'5076','6209','6213'}
skills={};items={};missing=[]
def publish(icon):
    source=icons/(icon.lower()+'.png')
    # BranchSys2's Icon group is flattened in the supplied client PNG export.
    flattened=icons/(icon.lower().replace('.icon.','.')+'.png')
    if not source.exists() and flattened.exists():source=flattened
    if not source.exists():missing.append(icon);return None
    key=icon.lower().replace('.','-')
    with Image.open(source) as im:
        for size in (32,64,128):
            target=dest/f'{key}-{size}.webp'
            if not target.exists():im.convert('RGBA').resize((size,size),Image.Resampling.NEAREST).save(target,lossless=True)
    return key
for path in skills_dir.rglob('*.xml'):
    for skill in ET.parse(path).getroot().findall('skill'):
        if skill.get('id') not in needed_skills:continue
        icon=skill.findtext('icon') or 'icon.skill'+skill.get('id').zfill(4)
        if icon.startswith('#'):
            icon=next((t.text.split()[0] for t in skill.findall('table') if t.get('name')==icon),'')
        key=publish(icon)
        if key:skills[skill.get('id')]=key
needed=set([736,737,1865,1867,1869,4037,6622,9625,9626,9627,*range(8594,8600),1463,1464,1465,1466,1467,1835])
extra=Path(sys.argv[4] if len(sys.argv)>4 else 'docs/item-metadata/icon-import-ids.json')
if extra.exists():needed.update(map(int,json.loads(extra.read_text(encoding='utf8'))))
with zipfile.ZipFile(items_zip) as z:
    for name in z.namelist():
        if not name.endswith('.xml'):continue
        for item in ET.fromstring(z.read(name)).iter('item'):
            if int(item.get('id','0')) not in needed:continue
            icon=next((s.get('val') for s in item.findall('set') if s.get('name')=='icon'),'')
            key=publish(icon)
            if key:items['l2_'+item.get('id')]=key
Path('webapp/art/l2-gameplay-icons.js').write_text('// Original Lineage II client icons by ID; generated by publish-gameplay-icons.py.\nexport const SKILL_ICONS='+json.dumps(skills,separators=(',',':'))+';\nexport const ITEM_ICONS='+json.dumps(items,separators=(',',':'))+';\nexport function originalIcon(key){return key?`<img class="mat-icon l2-client-icon" src="/art/l2-extra/${key}-32.webp" srcset="/art/l2-extra/${key}-64.webp 2x" width="32" height="32" alt="" decoding="async" draggable="false">`:\'\';}\n',encoding='utf8')
print(len(skills),'skill IDs,',len(items),'item IDs; missing',len(set(missing)))

if missing: print("Missing original icons: "+", ".join(sorted(set(missing))))
