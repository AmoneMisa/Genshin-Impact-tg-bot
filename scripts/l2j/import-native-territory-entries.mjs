import fs from 'node:fs';
import {execFileSync} from 'node:child_process';
import nativeWorld from '../../template/nativeWorld.js';
import {worldGeodata} from '../../functions/game/world/l2jGeodata.js';
import {nativeGroundAllowed} from '../../functions/game/world/nativeGround.js';
import {findNativePath} from '../../functions/game/world/nativeNavigation.js';
const file='template/nativeTerritoryEntries.js',entries=(await import(new URL('../../'+file,import.meta.url))).default;
for(const id of process.argv.slice(2)){
 const source=JSON.parse(execFileSync('python',['scripts/l2j/read-native-territories.py',id],{encoding:'utf8'}));
 const from=nativeWorld.towns[source.city],candidates=[],seen=new Set();
 for(const territory of source.territories)for(const [vertex,node] of territory.nodes.entries()){
  const low=worldGeodata.point({...node,z:territory.minZ}),high=worldGeodata.point({...node,z:territory.maxZ});
  // Only an unambiguous original layer inside the source Z interval is eligible.
  if(!low||!high||low.z!==high.z||low.z<territory.minZ||low.z>territory.maxZ||!low.nswe||!nativeGroundAllowed(low))continue;
  const key=[low.x,low.y,low.z].join(',');if(seen.has(key))continue;seen.add(key);
  candidates.push({point:low,territory,vertex,distance:Math.hypot(from.x-low.x,from.y-low.y)});
 }
 candidates.sort((a,b)=>a.distance-b.distance);let chosen;
 for(const candidate of candidates.slice(0,4)){
  const options={allowed:nativeGroundAllowed,stride:8,maxNodes:30000,heuristicWeight:2,margin:1024,reversible:true};
  let plan=findNativePath(from,candidate.point,options),direction='forward';
  if(!plan.ok){plan=findNativePath(candidate.point,from,options);direction='reverse';}
  console.log(id,'source vertex',candidate.point.x,candidate.point.y,candidate.point.z,plan.ok,plan.reason||'',plan.visited,direction);
  if(plan.ok&&plan.path.length<=512){chosen=candidate;break;}
 }
 if(!chosen)throw new Error(id+': no unambiguous source-boundary approach verified; nothing published');
 const {point:p,territory:t,vertex}=chosen,{x,y,z}=p;
 entries[id]={x,y,z,region:source.city,teleportGold:null,entryRoutes:[],access:{kind:'walk-only'},
  entrySource:{type:'TERRITORY_BOUNDARY',coordinateSource:'territory-node',originalEntrance:null,
   file:source.file,sha256:source.sha256,commit:nativeWorld.source.commit,zone:t.zone,vertex,
   npcIds:t.npcIds,polygon:t.nodes.map(n=>[n.x,n.y]),minZ:t.minZ,maxZ:t.maxZ,
   heightSource:'l2j-geodata',geodataCommit:worldGeodata.manifest.commit,
   selectionRule:'nearest-source-vertex-with-confirmed-ground-path'},
  polygon:[[x-5000,y-5000],[x+5000,y-5000],[x+5000,y+5000],[x-5000,y+5000]],selectionGeometry:'authored-extent'};
}
fs.writeFileSync(file,'// Source territory vertices and native geodata heights; generated by scripts/l2j/import-native-territory-entries.mjs.\nexport default '+JSON.stringify(entries,null,2)+';\n');
