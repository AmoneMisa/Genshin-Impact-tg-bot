"""Publish spatial combat data from the same H5 XML snapshot as our skill trees."""
from pathlib import Path
import xml.etree.ElementTree as ET
import json

root = Path(__file__).resolve().parents[2]
source = root / '.tmp/l2-high-five'
fields = {'targetType', 'castRange', 'affectRange', 'affectLimit', 'fanRange', 'hitTime', 'coolTime', 'reuseDelay'}
skills, weapons, players = {}, {}, {}
pole_extra = None
for path in sorted((source / 'all-skills').rglob('*.xml')):
    for skill in ET.parse(path).getroot().findall('skill'):
        if skill.get('id') == '3599':
            pole_extra = int(skill.findtext('./effects/effect/add[@stat="atkCountMax"]'))
        values = {node.tag: node.text.strip() for node in skill if node.tag in fields and node.text}
        refs = {v for v in values.values() if v.startswith('#')}
        tables = {node.get('name'): node.text.split() for node in skill.findall('table') if node.get('name') in refs}
        skills[skill.get('id')] = {**values, **({'tables': tables} if tables else {})}
for path in sorted((source / 'items').rglob('*.xml')):
    for item in ET.parse(path).getroot().findall('item'):
        if item.get('type') != 'Weapon':
            continue
        values = {node.get('name'): node.get('val') for node in item.findall('set')}
        stats = {node.get('type'): node.text for node in item.findall('stats/stat')}
        weapons.setdefault(item.get('name'), {'type': values.get('weapon_type'), 'range': float(stats.get('pAtkRange', 0)),
            'speed': float(stats.get('pAtkSpd', 0)), 'damageRange': values.get('damage_range'),
            'reuse': int(values.get('reuse_delay', 0)), 'mp': int(values.get('mp_consume', 0)),
            'extraTargets': pole_extra if item.find('./skills/skill[@id="3599"]') is not None else 0})
for path in sorted((source / 'players').rglob('*.xml')):
    tree = ET.parse(path).getroot()
    data = tree.find('staticData')
    if data is not None:
        players[tree.findtext('classId')] = {'range': float(data.findtext('baseAtkRange', '0')),
            'speed': float(data.findtext('basePAtkSpd', '0'))}
assert skills and weapons and players, 'Missing original H5 data; do not publish an empty catalog'
target = root / 'template/l2CombatSpatial.js'
target.write_text('// Generated by scripts/l2j/import-combat-spatial.py. H5 snapshot 9fb01cb20513e55190cdde8d91e41be2c0914f84.\n'
    + '\n'.join('export const ' + name + ' = ' + json.dumps(value, ensure_ascii=False, separators=(',', ':')) + ';'
        for name, value in [('SKILL_SPATIAL', skills), ('WEAPON_SPATIAL', weapons), ('PLAYER_SPATIAL', players)]) + '\n', encoding='utf-8')
print(f'Published {len(skills)} skills, {len(weapons)} weapons, {len(players)} player templates')
